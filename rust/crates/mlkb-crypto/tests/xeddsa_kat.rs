//! Signal XEdDSA cross-vectors, byte-for-byte (spec parent §5.4, §11 gate 1).
//!
//! # Provenance — read before touching a byte of the table
//!
//! Every `sig` below was produced by the **vendored Signal C**, through the
//! same extension the Python reference implementation calls:
//!
//! ```text
//! ml_kem_braid/crypto/_curve25519/_curve25519module.c
//!   calculateSignature -> curve25519_sign    (line 27)
//!   verifySignature    -> curve25519_verify  (line 37)
//! ```
//!
//! and each was checked to satisfy `curve25519_verify` before being recorded.
//! `seed` is the raw input to `generatePrivateKey` (i.e. pre-clamp) and
//! `public` is the C's own `generatePublicKey` output, so this file also pins
//! that Rust and C agree on key derivation.
//!
//! The first entry is the project's pre-existing Python KAT verbatim —
//! `_KAT_SIG_HEX` in `tests/test_xeddsa.py` (priv = clamp(bytes(range(32))),
//! msg = `b"MLKEMBraid KAT vector"`, Z = 64 zero bytes). It was not
//! regenerated; it is the same hex string that file already asserts.
//!
//! **None of these expected values came from this Rust implementation.** A KAT
//! that pins bytes our own code produced would be circular and worth nothing.
//! To regenerate, run the vendored C — never `sign`:
//!
//! ```text
//! uv run python -c "
//! from ml_kem_braid.crypto import backend
//! c = backend.load()
//! priv = c.generatePrivateKey(seed)
//! print(c.calculateSignature(z, priv, msg).hex())"
//! ```
//!
//! # What these vectors are chosen to catch
//!
//! 1. **`sig[63]`'s sign bit.** `curve25519_sign` keeps `A`'s Edwards sign bit
//!    and stashes it in `sig[63]` (`curve_sigs.c:26,34-35`); `curve25519_verify`
//!    reads it back (`curve_sigs.c:77-80`). Roughly half of all real Signal
//!    signatures have it set. Four vectors below do. An implementation that
//!    followed the *unbound* `xed25519_*` convention (`xeddsa.c:29-33`, which
//!    forces the bit to zero by negating `a`) fails all four, in both `sign`
//!    and `verify`.
//! 2. **What `hash_1` eats.** `crypto_sign_modified` hashes the clamped private
//!    key bytes verbatim (`sign_modified.c:26`), not the scalar reduced mod the
//!    group order. Feeding it the reduced scalar still round-trips against
//!    itself, so only a vector from the C side catches it — that is exactly
//!    what the existing Python KAT does.
//! 3. **Rejections the C does not perform.** `NO_REJECT`, near the bottom of
//!    this file, is a second table of inputs the C *accepts* despite being
//!    malformed — a non-canonical `s`, and a `u` whose encoding has bit 255
//!    set. Spec parent §5.4 makes an added rejection a defect, and these are
//!    the two most tempting ones to add: reducing/validating `s`, and the
//!    `fe_isreduced` guard the unbound `xed25519_verify` has (`xeddsa.c:65`)
//!    and `curve25519_verify` does not. Both were confirmed accepted by
//!    `curve25519_verify` before being recorded.

