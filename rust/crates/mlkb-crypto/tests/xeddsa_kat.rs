/// An RNG that hands out one fixed 64-byte `Z`, so `sign` becomes
/// deterministic and can be compared against a recorded vector.
///
/// It is deliberately strict: `sign` must ask for exactly 64 bytes, exactly
/// once. If the amount or number of draws ever changes, these tests fail
/// loudly rather than silently comparing against a differently-derived nonce.
struct FixedZ {
    z: [u8; 64],
    drawn: bool,
}

impl rand_core::TryRng for FixedZ {
    type Error = rand_core::Infallible;

    fn try_next_u32(&mut self) -> Result<u32, Self::Error> {
        panic!("sign must draw its nonce with fill_bytes, not next_u32")
    }

    fn try_next_u64(&mut self) -> Result<u64, Self::Error> {
        panic!("sign must draw its nonce with fill_bytes, not next_u64")
    }

    fn try_fill_bytes(&mut self, dst: &mut [u8]) -> Result<(), Self::Error> {
        assert!(!self.drawn, "sign drew randomness more than once");
        assert_eq!(dst.len(), 64, "sign drew {} bytes, expected 64", dst.len());
        self.drawn = true;
        dst.copy_from_slice(&self.z);
        Ok(())
    }
}

impl rand_core::TryCryptoRng for FixedZ {}

/// Spec parent §11 gate 1: `sign` reproduces the vendored Signal C byte for
/// byte, for the same key, message and `Z`.
#[test]
fn sign_reproduces_the_vendored_signal_c_byte_for_byte() {
    for v in VECTORS {
        let sk = X25519SecretKey::from_bytes(v.seed);
        let mut rng = FixedZ {
            z: v.z,
            drawn: false,
        };
        let got = xeddsa::sign(&sk, v.msg, &mut rng);
        assert_eq!(
            got,
            v.sig,
            "vector {}: signature differs from the vendored C\n  got {}\n  want {}",
            v.name,
            hex(&got),
            hex(&v.sig)
        );
    }
}

