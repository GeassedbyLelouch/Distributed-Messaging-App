/// The table must actually exercise the case finding 1 is about. Without this
/// guard, someone could prune the awkward vectors and leave a green suite that
/// proves nothing.
#[test]
fn the_table_covers_both_values_of_the_sign_bit() {
    let set = VECTORS.iter().filter(|v| v.sig[63] & 0x80 != 0).count();
    let clear = VECTORS.len() - set;
    assert!(
        set >= 4,
        "only {set} vectors have sig[63] bit 7 set; that is the half of \
         Signal's output space a sign-bit-0-only verifier rejects"
    );
    assert!(clear >= 4, "only {clear} vectors have sig[63] bit 7 clear");
}

/// A signature that verifies must stop verifying under any single-bit change,
/// under the wrong message, or under another vector's key.
#[test]
fn verify_rejects_tampered_vendored_signal_c_signatures() {
    for (index, v) in VECTORS.iter().enumerate() {
        let pk = X25519PublicKey::from_bytes(v.public);

        // Exhaustive on the first vector; for the rest, every byte at bit 0
        // plus an exhaustive sweep of byte 63, which is the byte carrying both
        // the sign bit and the range-checked bits. Keeping the full 512-flip
        // sweep on all nine vectors costs ~45s in a debug build and finds
        // nothing the reduced sweep misses.
        let exhaustive = index == 0;
        for byte in 0..64usize {
            let bits: &[u32] = if exhaustive || byte == 63 {
                &[0, 1, 2, 3, 4, 5, 6, 7]
            } else {
                &[0]
            };
            for &bit in bits {
                let mut bad = v.sig;
                bad[byte] ^= 1u8 << bit;
                assert!(
                    xeddsa::verify(&pk, v.msg, &bad).is_err(),
                    "vector {}: accepted a flip of bit {bit} of byte {byte}",
                    v.name
                );
            }
        }

        let mut other_msg = v.msg.to_vec();
        other_msg.push(0x00);
        assert!(
            xeddsa::verify(&pk, &other_msg, &v.sig).is_err(),
            "vector {}: accepted an extended message",
            v.name
        );

        for w in VECTORS {
            if w.public != v.public {
                let wrong = X25519PublicKey::from_bytes(w.public);
                assert!(
                    xeddsa::verify(&wrong, v.msg, &v.sig).is_err(),
                    "vector {}: accepted under {}'s key",
                    v.name,
                    w.name
                );
            }
        }
    }
}

/// The `s` range check the C performs (`open_modified.c:24`, `sm[63] & 224`
/// after `curve_sigs.c:80` clears bit 7) — and *only* that one. Bit 7 is the
/// public key's sign bit, so it is not part of the range check.
#[test]
fn the_s_range_check_matches_the_c() {
    for v in VECTORS {
        let pk = X25519PublicKey::from_bytes(v.public);
        for bit in [5u32, 6] {
            let mut bad = v.sig;
            bad[63] |= 1u8 << bit;
            assert!(
                xeddsa::verify(&pk, v.msg, &bad).is_err(),
                "vector {}: bit {bit} of s was not range-checked",
                v.name
            );
        }
    }
}

